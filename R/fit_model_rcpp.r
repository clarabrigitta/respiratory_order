settings <- list(iterations = 5000, burnin = 0, nrChains = 1)

results <- list()

for (n in seq_along(combinations)) {
  virus_name <- combinations[[n]]$name
  pathogen_name <- pathogen_map[[virus_name]]
  cat("Fitting combination", n, ":", virus_name)

  subdata <- data %>% filter(Pathogen == pathogen_name)

  local({
    n_local <- n
    data_local <- subdata
    # observed counts flattened once: this was rebuilt from the tibble on every
    # likelihood call, which is ~500k identical tibble subsets + matrix coercions
    obs_vec <- as.vector(as.matrix(subdata[, -1]))

    # prior_local <- createUniformPrior(
    #   lower = combinations[[n_local]]$lb,
    #   upper = combinations[[n_local]]$ub
    # )

    lb <- combinations[[n_local]]$lb
    ub <- combinations[[n_local]]$ub
    # prior median = imm_period; tune sdlog as needed
    imm_meanlog <- log(combinations[[n_local]]$imm_period)
    imm_sdlog <- combinations[[n_local]]$imm_sd

    prior_local <- createPrior(
      density = function(param) {
        ld_uniform <- sum(dunif(param[u_idx], min = lb[u_idx], max = ub[u_idx], log = TRUE))
        ld_imm <- dlnorm(param[idx$imm],
                         meanlog = imm_meanlog, sdlog = imm_sdlog,
                         log = TRUE)
        ld_uniform + ld_imm
      },
      sampler = function(n = 1) {
        u <- mapply(function(lo, hi) runif(n, lo, hi), lb[u_idx], ub[u_idx])
        d <- rlnorm(n, meanlog = imm_meanlog, sdlog = imm_sdlog)
        if (n == 1) c(u[1:10], d, u[11]) else cbind(u[, 1:10], d, u[, 11])
        },
      lower = c(lb[1:10], 0,   lb[12]),
      upper = c(ub[1:10], Inf, ub[12])
    )

    likelihood <- function(param) {
      detection_rates <- param[idx$det]
      p_sus_bands     <- param[idx$sus]
      imm_duration    <- param[idx$imm]
      imports         <- 10^param[idx$imp]

      model_out <- run_model_rcpp(p_sus_bands, n_local, imm_duration, imports)

      # equivalent to as.vector(sweep(model_out, 2, detection_rates, `*`)) but skips
      # sweep's array machinery; as.vector() is column-major, matching rep(each = nweeks)
      expected_vec <- as.vector(model_out) *
        rep(detection_rates, each = nrow(model_out))

      ll <- sum(dpois(obs_vec, expected_vec, log = TRUE))
      if (!is.finite(ll)) return(-1e10)
      ll
    }

    setup <- createBayesianSetup(
      likelihood = likelihood,
      prior = prior_local,
      parallel = FALSE,
      names = c(paste0("detection_", c("0to4","5to14","15to44","45to64","65plus")),
                paste0("sus_",       c("0to4","5to14","15to44","45to64","65plus")),
                "imm_duration", "log10_import")
    )

    set.seed(24)
    chains <- mclapply(1:4,
                       function(x) {
                         runMCMC(bayesianSetup = setup, sampler = "DEzs", settings = settings)
                       },
                       mc.cores = 4)
    out <- createMcmcSamplerList(chains)

    results[[virus_name]] <<- out
  })

  cat(" Done:", virus_name, "\n")
}

