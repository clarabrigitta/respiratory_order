# ---- C++-backed model runner ----

# Identical interface to run_model() in fit_model.r, but uses the Rcpp ODE solver.
# Returns a matrix of weekly incidence counts (rows = weeks, cols = 5 age bands).
run_model_rcpp <- function(p_sus_bands, n, imm_days, imports = 1) {
  sigma <- 1 / combinations[[n]]$inc_period
  gamma <- 1 / combinations[[n]]$inf_period
  bg    <- imports / sum(tots)
  
  R_init <- tots * (1 - p_sus_bands[band_of_group])
  S_init <- tots - R_init
  E_init <- bg * S_init / sigma         
  I_init <- bg * S_init / gamma
  
  y0_mat <- rbind(S = S_init - E_init - I_init,
                  E = E_init,
                  I = I_init,
                  R = R_init)
  y0 <- setNames(as.vector(y0_mat),
                 paste0(rep(c("S", "E", "I", "R"), 9), rep(1:9, each = 4)))
  
  out <- seirs_rcpp(
    y0 = y0,
    times = times,
    parms = list(
      sigma = sigma,
      gamma = gamma,
      omega = 1 / imm_days,
      p_inf = combinations[[n]]$p_inf,
      bg    = bg,
      mu_b  = daily_births,
      mu_d  = hazard_death
    ),
    contacts_prepped = contacts_prepped
  )

  daily_inc <- out[, inc_cols, drop = FALSE]   # inc_cols precomputed at module level

  # Aggregate age groups to match observed data (same as fit_model.r)
  daily_agg <- cbind(
    daily_inc[, 1],                                             # 0-4
    daily_inc[, 2] + daily_inc[, 3],                            # 5-14
    daily_inc[, 4] + daily_inc[, 5] + daily_inc[, 6],           # 15-44
    daily_inc[, 7] + daily_inc[, 8],                            # 45-64
    daily_inc[, 9]                                              # 65+
  )

  rowsum(daily_agg, week_group)
}

